#!/usr/bin/env python3
"""Regenerates qml/components/Icons.qml from the @phosphor-icons/web CSS.
   npm pack @phosphor-icons/web@2.1.2 && tar xzf *.tgz && python3 tools/gen_icons.py package/src
Add icon names to WANT to expose more glyphs."""
import re, sys, pathlib

WANT = """gear magnifying-glass folder-plus trash arrow-clockwise sidebar-simple squares-four
x x-circle check check-circle warning warning-circle info caret-left caret-right caret-down caret-up copy image plus minus
arrows-out film-strip play pause arrow-up download-simple arrow-square-out upload-simple note-pencil key lock-simple
folder-open arrow-right arrow-left dots-three command export file-image swap list-magnifying-glass sparkle lightning
scissors cursor hand hand-grabbing text-t text-aa note arrow-u-up-left arrow-u-up-right magnifying-glass-plus
magnifying-glass-minus corners-out frame-corners map-trifold dots-nine grid-four square align-left align-right align-top
align-bottom align-center-horizontal align-center-vertical arrows-out-line-horizontal arrows-out-line-vertical lock
lock-open stack-simple arrow-line-up arrow-line-down copy-simple clipboard palette paint-brush pencil-simple file-pdf file
play-circle speaker-high speaker-slash vault selection selection-plus text-h-one dots-three-vertical arrow-bend-up-right
share-network crosshair rectangle dots-six file-text stack-plus corners-in monitor tree-structure arrow-clockwise
sidebar eye eye-slash tag""".split()

base = pathlib.Path(sys.argv[1])
css = (base / "regular/style.css").read_text()
codes = dict(re.findall(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
missing = [w for w in WANT if w not in codes]
if missing:
    print("missing:", missing)
out = ['pragma Singleton', 'import QtQuick', '',
       '// Phosphor Icons (MIT), files in resources/fonts. Generated by tools/gen_icons.py. Do not edit by hand.',
       'QtObject {', '    readonly property var map: ({']
out.append(",\n".join(f'        "{w}": "\\u{codes[w]}"' for w in WANT if w in codes))
out += ['    })', '    function glyph(name) { return map[name] || "" }', '}']
(pathlib.Path(__file__).resolve().parent.parent / "qml/components/Icons.qml").write_text("\n".join(out) + "\n")
print(len(WANT) - len(missing), "icons written")
